        entries.forEach(entry => {
          if (entry.isIntersecting) {
            entry.target.classList.add('animate-in');
          }
        });
      }, observerOptions);

      document.querySelectorAll('[data-scroll]').forEach(el => {
        observer.observe(el);
      });
    },
    
